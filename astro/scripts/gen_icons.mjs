// Generates src/styles/icons.css (bundled into the site CSS) from src/lib/icons.mjs.
//
// Icons ship as CSS data URIs, built here with @iconify/utils, so:
//   - no icon font / no extra request — they ride in the already-cached site CSS
//   - each use is a ~40-byte <span class="ic ic-read"> (cheap on the 4k-card browse page)
//   - a mono icon (one that draws in currentColor) is a mask tinted by the text `color`;
//     a multicolour icon is a background image in its own colours
// Output is committed; rerun only when icons.mjs changes: `pnpm run gen:icons`.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getIconData, iconToSVG, iconToHTML, svgToURL } from '@iconify/utils';
import { optimize } from 'svgo';
import { ICONS, PILL_ICONS, parseIcon } from '../src/lib/icons.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, '..', 'src', 'styles', 'icons.css');

// Fetch just the icons we use, per Iconify set, from the Iconify API (avoids multi-MB
// icon-set packages).
const wanted = new Map();
for (const value of Object.values(ICONS)) {
  const { set, name } = parseIcon(value);
  if (!wanted.has(set)) wanted.set(set, new Set());
  wanted.get(set).add(name);
}
const fetched = new Map();
for (const [set, names] of wanted) {
  const url = `https://api.iconify.design/${set}.json?icons=${[...names].join(',')}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`iconify API ${res.status} for ${url}`);
  const data = await res.json();
  if (data.not_found?.length) throw new Error(`icons not found in ${set}: ${data.not_found.join(', ')}`);
  fetched.set(set, data);
}

// One rule per distinct icon: semantic names that share an icon (watch/video, app/phone)
// share its data URI. Classes read .ic-read, not .ic-book-open-24.
const selectors = new Map();
for (const [key, value] of Object.entries(ICONS)) {
  if (!selectors.has(value)) selectors.set(value, []);
  selectors.get(value).push(`.ic-${key}`);
  if (PILL_ICONS.includes(key)) selectors.get(value).push(`.pill[data-r=${key}]:before`);
}

// SVGO shrinks the icon CSS by about a third. Most of it is rounding path coordinates to
// one decimal (0.1 of a 24-unit grid is under 0.1px at the sizes we draw) and replacing
// Iconify's random gradient ids with one-letter ones.
const minify = (svg) => optimize(svg, { multipass: true, floatPrecision: 1 }).data;

let css = `/* GENERATED by scripts/gen_icons.mjs from src/lib/icons.mjs — do not edit by hand.
 * Fluent Color icons via Iconify (${[...wanted.keys()].join(', ')}). */
.ic,.pill:before{display:inline-block;width:1em;height:1em;flex:0 0 auto;vertical-align:-0.14em;background-color:currentColor;-webkit-mask:var(--svg) 0 0/100% 100% no-repeat;mask:var(--svg) 0 0/100% 100% no-repeat}
`;
for (const [value, sels] of selectors) {
  const { set, name } = parseIcon(value);
  // getIconData resolves aliases and merges set-level width/height into the icon.
  const icon = getIconData(fetched.get(set), name);
  if (!icon) throw new Error(`icon ${set}:${name} missing from API response`);
  const svg = iconToSVG(icon);
  const mono = svg.body.includes('currentColor');
  // A mask only reads alpha, and currentColor inside a data-URI image is undefined.
  const body = mono ? svg.body.replace(/currentColor/g, 'black') : svg.body;
  const url = svgToURL(minify(iconToHTML(body, { ...svg.attributes, width: '24', height: '24' })));
  const rule = mono ? `--svg:${url}` : `background:${url} 0 0/100% 100% no-repeat;-webkit-mask:none;mask:none`;
  css += `${sels.join(',')}{${rule}}\n`;
}

writeFileSync(OUT, css);
console.log(`wrote ${OUT}: ${Object.keys(ICONS).length} icons, ${css.length} bytes`);
